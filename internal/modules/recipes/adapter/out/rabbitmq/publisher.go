package rabbitmq

import (
	"context"
	"encoding/json"
	"fmt"
	"time"

	"recipes-desk/internal/infra/messagebus"
	"recipes-desk/internal/infra/messagebus/rabbitmq"
	"recipes-desk/internal/modules/recipes/application/ports/out"
	"recipes-desk/internal/modules/recipes/domain/events"
)

const (
	exchangeName = "recipes.topic"

	recipeCreatedRoutingKey = "recipes.created"
	recipeDeletedRoutingKey = "recipes.deleted"
)

// Verify Publisher implements outports.EventPublisher.
var _ out.EventPublisher = (*Publisher)(nil)

// Publisher publishes recipe domain events to RabbitMQ.
type Publisher struct {
	producer messagebus.Publisher
}

// NewPublisher creates a new RabbitMQ event publisher.
func NewPublisher(producer *rabbitmq.Producer) *Publisher {
	return &Publisher{
		producer: producer,
	}
}

// PublishRecipeCreated publishes a recipe.created event.
func (p *Publisher) PublishRecipeCreated(ctx context.Context, event events.RecipeCreated) error {
	return p.publish(ctx, recipeCreatedRoutingKey, event)
}

// PublishRecipeDeleted publishes a recipe.deleted event.
func (p *Publisher) PublishRecipeDeleted(ctx context.Context, event events.RecipeDeleted) error {
	return p.publish(ctx, recipeDeletedRoutingKey, event)
}

func (p *Publisher) publish(ctx context.Context, routingKey string, payload any) error {
	body, err := json.Marshal(payload)
	if err != nil {
		return fmt.Errorf("failed to marshal event payload: %w", err)
	}

	//nolint:exhaustruct // ID auto-generated by producer
	msg := messagebus.Message{
		Type:      routingKey,
		Timestamp: time.Now(),
		Source:    "recipes",
		Payload:   body,
	}

	return p.producer.Publish(ctx, exchangeName, routingKey, msg)
}
