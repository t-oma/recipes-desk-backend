const _testDBName = "test_auth"

func TestIntegration_MongoRepository_Create(t *testing.T) {
	db, cleanup := testutils.SetupMongoContainer(t, _testDBName)
	defer cleanup()

	repo := mongorepo.NewUsers(db)
	ctx := context.Background()

	t.Run("create new user", func(t *testing.T) {
		user := fixtures.NewUser(t, "test@example.com")

		created, err := repo.Create(ctx, user)
		require.NoError(t, err)

		// Verify ID was set
		assert.NotEmpty(t, created.ID().String())
		// Verify timestamps were set
		assert.False(t, created.CreatedAt().IsZero())
		assert.False(t, created.PasswordUpdatedAt().IsZero())
	})

	t.Run("create user with provided ID", func(t *testing.T) {
		existingID := primitive.NewObjectID().Hex()
		user := fixtures.NewUserWithOptions(t,
			fixtures.WithEmail("existing@example.com"),
		)
		// Assign specific ID
		id, _ := valueobject.NewUserID(existingID)
		user.AssignID(id)

		created, err := repo.Create(ctx, user)
		require.NoError(t, err)

		// ID should be preserved or regenerated by repository
		assert.NotEmpty(t, created.ID().String())
	})
}

func TestIntegration_MongoRepository_FindByID(t *testing.T) {
	db, cleanup := testutils.SetupMongoContainer(t, _testDBName)
	defer cleanup()

	repo := mongorepo.NewUsers(db)
	ctx := context.Background()

	// Create a test user first
	user := fixtures.NewUser(t, "findbyid@example.com")
	created, err := repo.Create(ctx, user)
	require.NoError(t, err)
	id := created.ID().String()

	t.Run("find existing user", func(t *testing.T) {
		found, err := repo.FindByID(ctx, id)
		require.NoError(t, err)

		assert.Equal(t, id, found.ID().String())
		assert.Equal(t, user.Email().String(), found.Email().String())
		assert.Equal(t, user.FirstName().String(), found.FirstName().String())
		assert.Equal(t, user.LastName().String(), found.LastName().String())
	})

	t.Run("find non-existent user", func(t *testing.T) {
		nonExistentID := primitive.NewObjectID().Hex()
		_, err := repo.FindByID(ctx, nonExistentID)
		assert.ErrorIs(t, err, domain.ErrUserNotFound)
	})

	t.Run("find with invalid ID format", func(t *testing.T) {
		_, err := repo.FindByID(ctx, "invalid-id-format")
		assert.ErrorIs(t, err, domain.ErrUserNotFound)
	})
}

